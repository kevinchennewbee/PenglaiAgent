#!/usr/bin/env node
/**
 * sync-schema-versions.mjs — 从 packages/protocol 生成各端契约常量（单一真相源）。
 *
 * 为何存在：
 *   0.4.0 曾在 protocol / Rust 壳 / build-runtime manifest / verify-runtime
 *   四处硬编码 DATABASE_SCHEMA_VERSION，schema 从 1 涨到 6 时只改了
 *   protocol+host，打包壳仍冻在 1 → 用户装完 DMG 直接 RuntimeGate 红框。
 *
 * 规则：
 *   - 唯一手写来源：packages/protocol/src/index.ts
 *   - 本脚本生成：
 *       packages/desktop/src-tauri/src/schema_versions.rs
 *       packages/host/scripts/schema-versions.generated.json
 *   - build-runtime / verify-runtime / release-check 只读 generated JSON
 *   - Rust 壳 include! 生成的 schema_versions.rs
 *
 * 用法：
 *   node scripts/sync-schema-versions.mjs
 *   node scripts/sync-schema-versions.mjs --check   # CI：与产物不一致则 exit 1
 */

import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PROTOCOL = path.join(ROOT, "packages/protocol/src/index.ts");
const RUST_OUT = path.join(ROOT, "packages/desktop/src-tauri/src/schema_versions.rs");
const JSON_OUT = path.join(ROOT, "packages/host/scripts/schema-versions.generated.json");

function readConst(source, name) {
  const re = new RegExp(
    `export\\s+const\\s+${name}\\s*=\\s*(?:([0-9]+)|"([^"]+)")\\s*as\\s+const`,
  );
  const m = source.match(re);
  if (!m) throw new Error(`cannot find export const ${name} in protocol/src/index.ts`);
  return m[1] !== undefined ? Number(m[1]) : m[2];
}

function renderRust(versions) {
  return `// GENERATED by scripts/sync-schema-versions.mjs — DO NOT EDIT.
// Source of truth: packages/protocol/src/index.ts
// Regenerate: node scripts/sync-schema-versions.mjs

pub const PROTOCOL_SCHEMA_VERSION: u64 = ${versions.protocolSchemaVersion};
pub const DATABASE_SCHEMA_VERSION: u64 = ${versions.databaseSchemaVersion};
pub const PRODUCT_VERSION: &str = "${versions.productVersion}";
pub const MIN_DESKTOP_VERSION: &str = "${versions.minimumDesktopVersion}";
`;
}

function renderJson(versions) {
  return `${JSON.stringify(versions, null, 2)}\n`;
}

function main() {
  const check = process.argv.includes("--check");
  const source = fs.readFileSync(PROTOCOL, "utf8");
  const versions = {
    protocolSchemaVersion: readConst(source, "SCHEMA_VERSION"),
    databaseSchemaVersion: readConst(source, "DATABASE_SCHEMA_VERSION"),
    productVersion: readConst(source, "PRODUCT_VERSION"),
    minimumDesktopVersion: readConst(source, "MIN_DESKTOP_VERSION"),
    source: "packages/protocol/src/index.ts",
    generatedBy: "scripts/sync-schema-versions.mjs",
  };

  if (typeof versions.protocolSchemaVersion !== "number") {
    throw new Error("SCHEMA_VERSION must be numeric");
  }
  if (typeof versions.databaseSchemaVersion !== "number") {
    throw new Error("DATABASE_SCHEMA_VERSION must be numeric");
  }

  const rust = renderRust(versions);
  const json = renderJson(versions);

  if (check) {
    const rustOk = fs.existsSync(RUST_OUT) && fs.readFileSync(RUST_OUT, "utf8") === rust;
    const jsonOk = fs.existsSync(JSON_OUT) && fs.readFileSync(JSON_OUT, "utf8") === json;
    if (!rustOk || !jsonOk) {
      console.error(
        "[sync-schema-versions] generated files are stale; run: node scripts/sync-schema-versions.mjs",
      );
      process.exit(1);
    }
    console.log(
      `[sync-schema-versions] ok protocol=${versions.protocolSchemaVersion} database=${versions.databaseSchemaVersion}`,
    );
    return;
  }

  fs.mkdirSync(path.dirname(RUST_OUT), { recursive: true });
  fs.mkdirSync(path.dirname(JSON_OUT), { recursive: true });
  fs.writeFileSync(RUST_OUT, rust);
  fs.writeFileSync(JSON_OUT, json);
  console.log(
    `[sync-schema-versions] wrote database=${versions.databaseSchemaVersion} protocol=${versions.protocolSchemaVersion}`,
  );
  console.log(`  → ${path.relative(ROOT, RUST_OUT)}`);
  console.log(`  → ${path.relative(ROOT, JSON_OUT)}`);
}

main();
